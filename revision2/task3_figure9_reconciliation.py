"""Task 3: reconcile Figure 9 medians with Tables 11 and 12.

The paper's Figure 9 is generated by ``fig_energy_overview`` in
``scripts/swopp3_analysis.py``.  This script reproduces every relevant summary
statistic from the manuscript-number File A outputs and marks the statistic
used by the figure annotations.
"""

from __future__ import annotations

import argparse
from pathlib import Path
from typing import Any

import numpy as np
import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "revision2"
CMA_ROOT = ROOT / "output" / "sweep_combined"
BERS_ROOT = ROOT / "output" / "sweep_combined_fms_strict"
TEAM = "IEUniversity-1"

CASES = {
    "AO_noWPS": {"corridor": "Atlantic", "wps": "Disabled", "gc": "AGC_noWPS"},
    "AO_WPS": {"corridor": "Atlantic", "wps": "Enabled", "gc": "AGC_WPS"},
    "PO_noWPS": {"corridor": "Pacific", "wps": "Disabled", "gc": "PGC_noWPS"},
    "PO_WPS": {"corridor": "Pacific", "wps": "Enabled", "gc": "PGC_WPS"},
}
STRATEGIES = ("GC", "CMA-ES", "BERS")

# Rounded manuscript values in current Tables 11 and 12.
TABLE11 = {
    ("AO_noWPS", "GC"): (310.3, None),
    ("AO_noWPS", "CMA-ES"): (220.2, 29.0),
    ("AO_noWPS", "BERS"): (206.2, 33.6),
    ("AO_WPS", "GC"): (253.3, None),
    ("AO_WPS", "CMA-ES"): (159.9, 36.9),
    ("AO_WPS", "BERS"): (139.5, 44.9),
    ("PO_noWPS", "GC"): (251.7, None),
    ("PO_noWPS", "CMA-ES"): (200.2, 20.5),
    ("PO_noWPS", "BERS"): (194.8, 22.6),
    ("PO_WPS", "GC"): (158.0, None),
    ("PO_WPS", "CMA-ES"): (87.3, 44.8),
    ("PO_WPS", "BERS"): (64.1, 59.4),
}
TABLE12_BERS_VS_GC = {
    "AO_noWPS": 27.5,
    "AO_WPS": 38.9,
    "PO_noWPS": 17.5,
    "PO_WPS": 55.2,
}


def outlier_mask(series: pd.Series, iqr_factor: float = 5.0) -> pd.Series:
    """Mirror ``scripts.swopp3_analysis._outlier_mask`` exactly."""
    q1, q3 = series.quantile(0.25), series.quantile(0.75)
    iqr = q3 - q1
    return (series >= q1 - iqr_factor * iqr) & (series <= q3 + iqr_factor * iqr)


def _path(strategy: str, case: str) -> Path:
    spec = CASES[case]
    if strategy == "GC":
        return CMA_ROOT / f"{TEAM}-{spec['gc']}.csv"
    root = CMA_ROOT if strategy == "CMA-ES" else BERS_ROOT
    return root / f"{TEAM}-{case}.csv"


def read_energy(strategy: str, case: str) -> pd.DataFrame:
    """Read one File A energy series and enforce the 366 unique departures."""
    path = _path(strategy, case)
    frame = pd.read_csv(
        path,
        usecols=["departure_time_utc", "energy_cons_mwh"],
        dtype={"departure_time_utc": str, "energy_cons_mwh": float},
    )
    if len(frame) != 366 or frame["departure_time_utc"].nunique() != 366:
        raise ValueError(f"Expected 366 unique departures in {path}, got {len(frame)}")
    if not np.isfinite(frame["energy_cons_mwh"]).all():
        raise ValueError(f"Non-finite energy in {path}")
    return frame


def energy_statistics(
    energy: pd.Series,
    paired_gc_energy: pd.Series,
    marginal_gc_energy: pd.Series | None = None,
) -> dict[str, float]:
    """Return the six statistics required by the reviewer for paired data."""
    values = energy.to_numpy(dtype=np.float64)
    gc_values = paired_gc_energy.to_numpy(dtype=np.float64)
    if len(values) != len(gc_values) or len(values) == 0:
        raise ValueError("Energy and GC series must be non-empty and equally long")
    marginal_gc = (
        paired_gc_energy if marginal_gc_energy is None else marginal_gc_energy
    ).to_numpy(dtype=np.float64)
    if len(marginal_gc) == 0:
        raise ValueError("Marginal GC series must be non-empty")
    paired = 100.0 * (gc_values - values) / gc_values
    mean_energy = float(np.mean(values))
    median_energy = float(np.median(values))
    gc_mean = float(np.mean(marginal_gc))
    gc_median = float(np.median(marginal_gc))
    return {
        "median_energy_mwh": median_energy,
        "mean_energy_mwh": mean_energy,
        "median_paired_saving_vs_gc_pct": float(np.median(paired)),
        "mean_paired_saving_vs_gc_pct": float(np.mean(paired)),
        "saving_of_mean_energies_vs_gc_pct": 100.0 * (gc_mean - mean_energy) / gc_mean,
        "saving_of_median_energies_vs_gc_pct": 100.0
        * (gc_median - median_energy)
        / gc_median,
    }


def compute() -> pd.DataFrame:
    """Return one Figure/Table reconciliation row per case and strategy."""
    rows: list[dict[str, Any]] = []
    for case, spec in CASES.items():
        gc_raw = read_energy("GC", case)
        gc_plot = gc_raw.loc[outlier_mask(gc_raw["energy_cons_mwh"])].copy()
        gc_by_dep = gc_raw.set_index("departure_time_utc")["energy_cons_mwh"]
        for strategy in STRATEGIES:
            raw = read_energy(strategy, case)
            plotted = raw.loc[outlier_mask(raw["energy_cons_mwh"])].copy()
            joined = plotted.join(
                gc_by_dep,
                on="departure_time_utc",
                rsuffix="_gc",
                validate="one_to_one",
            )
            stats = energy_statistics(
                joined["energy_cons_mwh"],
                joined["energy_cons_mwh_gc"],
                gc_plot["energy_cons_mwh"],
            )
            table11_mean, table11_saving = TABLE11[(case, strategy)]
            row = {
                "case": case,
                "corridor": spec["corridor"],
                "wps": spec["wps"],
                "strategy": strategy,
                "gc_baseline_case": spec["gc"],
                "gc_baseline_is_same_wps_mode": True,
                "n_file_a": len(raw),
                "n_figure_after_iqr5_filter": len(plotted),
                "n_figure_outliers_removed": len(raw) - len(plotted),
                **stats,
                "figure_annotation_uses_saving_of_median_energies": strategy != "GC",
                "figure_annotation_rounded_integer_pct": (
                    int(np.rint(stats["saving_of_median_energies_vs_gc_pct"]))
                    if strategy != "GC"
                    else np.nan
                ),
                "table11_mean_energy_reported_mwh": table11_mean,
                "table11_mean_energy_reproduced_1dp": round(stats["mean_energy_mwh"], 1)
                == table11_mean,
                "table11_saving_reported_pct": table11_saving,
                "table11_saving_reproduced_1dp": (
                    True
                    if table11_saving is None
                    else round(stats["saving_of_mean_energies_vs_gc_pct"], 1)
                    == table11_saving
                ),
                "table12_bers_vs_gc_mean_paired_reported_pct": (
                    TABLE12_BERS_VS_GC[case] if strategy == "BERS" else np.nan
                ),
                "table12_bers_vs_gc_mean_paired_reproduced_1dp": (
                    round(stats["mean_paired_saving_vs_gc_pct"], 1)
                    == TABLE12_BERS_VS_GC[case]
                    if strategy == "BERS"
                    else np.nan
                ),
            }
            rows.append(row)
    result = pd.DataFrame(rows)
    checks = result[
        [
            "table11_mean_energy_reproduced_1dp",
            "table11_saving_reproduced_1dp",
        ]
    ].to_numpy(dtype=bool)
    if not checks.all():
        raise AssertionError("At least one Table 11 value was not reproduced")
    bers_checks = result.loc[
        result["strategy"] == "BERS",
        "table12_bers_vs_gc_mean_paired_reproduced_1dp",
    ].astype(bool)
    if not bers_checks.all():
        raise AssertionError("At least one Table 12 BERS-vs-GC mean was not reproduced")
    return result


def write_report(frame: pd.DataFrame, path: Path) -> None:
    """Write the Figure 9 audit and a caption sentence."""
    annotation_rows = frame[frame["strategy"] != "GC"]
    lines = [
        "# Task 3 report: Figure 9 statistic",
        "",
        "## Exact plotting statistic",
        "",
        "The plotting code is `fig_energy_overview` in `scripts/swopp3_analysis.py`. "
        "Its `violinplot(..., showmedians=True)` call draws the median line, and "
        'the following styling sets `vp["cmedians"]` to white. Therefore each '
        "white bar is the median voyage energy (MWh) of that violin.",
        "",
        "For each optimized violin, the annotation is computed as "
        "`100 * (median(GC energies) - median(strategy energies)) / median(GC energies)`, "
        "then displayed with zero decimal places. It is the saving of the two marginal "
        "median energies. It is **not** the median of the 366 paired per-departure savings.",
        "",
        "The GC comparator is the great-circle case with the same propulsion mode: "
        "AGC_noWPS for AO_noWPS, AGC_WPS for AO_WPS, PGC_noWPS for PO_noWPS, and "
        "PGC_WPS for PO_WPS.",
        "",
        "## Reproduced annotations",
        "",
        "<!-- prettier-ignore -->",
        "| Case | Strategy | median energy (MWh) | figure saving of medians (%) | rounded annotation | median paired saving (%) |",
        "|---|---|---:|---:|---:|---:|",
    ]
    for row in annotation_rows.itertuples(index=False):
        lines.append(
            f"| {row.case} | {row.strategy} | {row.median_energy_mwh:.6f} | "
            f"{row.saving_of_median_energies_vs_gc_pct:.6f} | "
            f"{int(row.figure_annotation_rounded_integer_pct)}% | "
            f"{row.median_paired_saving_vs_gc_pct:.6f} |"
        )
    lines.extend(
        [
            "",
            "All File A series contain 366 departures, and the plotting script's 5-IQR "
            "filter removes zero rows in these manuscript-number roots. The CSV reproduces "
            "every Table 11 mean energy and saving at the published one-decimal precision, "
            "and every Table 12 BERS-versus-GC mean paired saving at that precision.",
            "",
            "## Suggested caption sentence",
            "",
            '"White bars mark the median voyage energy across the 366 departures; percentage '
            "annotations give the reduction of each strategy's median energy relative to the "
            'median of the great-circle baseline with the same propulsion mode."',
            "",
            "A companion sentence in the text should say: Table 11 instead reports reductions "
            "computed from mean energies, while Table 12 reports the mean of paired "
            "per-departure percentage reductions.",
            "",
            "Adding mean markers to the violin was not necessary: the ambiguity is resolved by "
            "the corrected caption, and the existing Table 11 already supplies the means.",
        ]
    )
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")


def main() -> None:
    """Run the Figure 9 reconciliation and write Task 3 outputs."""
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output-dir", type=Path, default=OUT)
    args = parser.parse_args()
    args.output_dir.mkdir(parents=True, exist_ok=True)
    frame = compute()
    frame.to_csv(args.output_dir / "task3_figure9_reconciliation.csv", index=False)
    write_report(frame, args.output_dir / "task3_report.md")
    print(frame.to_string(index=False))


if __name__ == "__main__":
    main()
